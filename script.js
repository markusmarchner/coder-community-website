let currentLanguage = translations[localStorage.getItem("coder-language")]
  ? localStorage.getItem("coder-language")
  : "de";
let currentVideo = "tagging";

const featureVideoFrame = document.querySelector("#feature-video");
const tabs = document.querySelectorAll(".video-tab");
const languageButtons = document.querySelectorAll(".language-option");
const kicker = document.querySelector("#feature-kicker");
const title = document.querySelector("#feature-title");
const description = document.querySelector("#feature-description");
const metaDescription = document.querySelector('meta[name="description"]');

function applyText(language) {
  const dictionary = translations[language] || translations.de;
  const pageTitleKey = document.body.dataset.pageTitleKey || "pageTitle";
  const metaDescriptionKey =
    document.body.dataset.metaDescriptionKey || "metaDescription";

  document.documentElement.lang = language;
  document.title = dictionary[pageTitleKey] || dictionary.pageTitle;

  if (metaDescription) {
    metaDescription.setAttribute(
      "content",
      dictionary[metaDescriptionKey] || dictionary.metaDescription,
    );
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-attr]").forEach((element) => {
    const pairs = element.dataset.i18nAttr.split(",");
    pairs.forEach((pair) => {
      const [attribute, key] = pair.split(":").map((value) => value.trim());
      if (attribute && key && dictionary[key]) {
        element.setAttribute(attribute, dictionary[key]);
      }
    });
  });
}

function consentMarkup() {
  const dictionary = translations[currentLanguage] || translations.de;

  return `
    <div class="video-consent-content">
      <p>${dictionary.youtubeNotice}</p>
      <button class="button primary" type="button" data-load-video>
        ${dictionary.youtubeButton}
      </button>
    </div>
  `;
}

function loadYouTubeVideo(frame) {
  const videoId = frame.dataset.videoId;
  const videoTitle = frame.dataset.videoTitle || "Coder Video";

  if (!videoId) {
    return;
  }

  frame.classList.remove("video-consent");
  frame.innerHTML = `
    <iframe
      src="https://www.youtube-nocookie.com/embed/${videoId}"
      title="${videoTitle}"
      loading="lazy"
      allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
      allowfullscreen
    ></iframe>
  `;
}

function resetVideoFrame(frame, videoId, videoTitle) {
  if (!frame) {
    return;
  }

  frame.dataset.videoId = videoId;
  frame.dataset.videoTitle = videoTitle;
  frame.classList.add("video-consent");
  frame.innerHTML = consentMarkup();
}

function selectVideo(key) {
  const videos = videoContent[currentLanguage] || videoContent.de;
  const video = videos[key] || videos.tagging;

  currentVideo = key;

  if (!video || !featureVideoFrame || !kicker || !title || !description) {
    return;
  }

  resetVideoFrame(featureVideoFrame, video.id, `Coder ${video.label} Video`);
  kicker.textContent = video.label;
  title.textContent = video.title;
  description.textContent = video.description;

  tabs.forEach((tab) => {
    const tabVideo = videos[tab.dataset.video];
    const isActive = tab.dataset.video === key;

    if (tabVideo) {
      tab.textContent = tabVideo.label;
    }

    tab.classList.toggle("active", isActive);
    tab.setAttribute("aria-pressed", String(isActive));
  });
}

function setLanguage(language) {
  if (!translations[language]) {
    return;
  }

  currentLanguage = language;
  localStorage.setItem("coder-language", language);
  applyText(language);
  selectVideo(currentVideo);

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

tabs.forEach((tab) => {
  tab.addEventListener("click", () => selectVideo(tab.dataset.video));
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

document.addEventListener("click", (event) => {
  const loadButton = event.target.closest("[data-load-video]");
  if (!loadButton) {
    return;
  }

  const frame = loadButton.closest("[data-youtube-frame]");
  if (frame) {
    loadYouTubeVideo(frame);
  }
});

setLanguage(currentLanguage);
